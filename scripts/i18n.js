function getLanguage() {
  const saved = localStorage.getItem(LANGUAGE_KEY);
  return saved === 'mr' ? 'mr' : 'en';
}

function setLanguage(lang) {
  const next = lang === 'mr' ? 'mr' : 'en';
  localStorage.setItem(LANGUAGE_KEY, next);
  document.documentElement.setAttribute('data-lang', next);
  applyTranslations(document);
  updateLanguageToggleUI();
  if (typeof updateThemeToggleButton === 'function') {
    const theme = document.documentElement.getAttribute('data-theme') || 'light';
    updateThemeToggleButton(theme);
  }
  window.dispatchEvent(new CustomEvent('farmaLanguageChanged', { detail: { lang: next } }));
}

function t(key, vars = null) {
  const lang = getLanguage();
  const table = translations[lang] || {};
  let str = table[key] || key;
  if (vars && typeof vars === 'object') {
    Object.keys(vars).forEach(k => {
      const val = vars[k];
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(val));
    });
  }
  return str;
}

function parseVars(el) {
  const raw = el.getAttribute('data-i18n-vars');
  if (!raw) return null;
  try {
    return JSON.parse(raw);
  } catch (e) {
    return null;
  }
}

function translateElement(el) {
  if (!el || el.nodeType !== 1) return;
  if (el.hasAttribute('data-i18n')) {
    const key = el.getAttribute('data-i18n');
    const vars = parseVars(el);
    el.textContent = t(key, vars);
  }
  if (el.hasAttribute('data-i18n-html')) {
    const key = el.getAttribute('data-i18n-html');
    const vars = parseVars(el);
    el.innerHTML = t(key, vars);
  }
  if (el.hasAttribute('data-i18n-placeholder')) {
    const key = el.getAttribute('data-i18n-placeholder');
    const vars = parseVars(el);
    el.setAttribute('placeholder', t(key, vars));
  }
  if (el.hasAttribute('data-i18n-title')) {
    const key = el.getAttribute('data-i18n-title');
    const vars = parseVars(el);
    el.setAttribute('title', t(key, vars));
  }
  if (el.hasAttribute('data-i18n-tooltip')) {
    const key = el.getAttribute('data-i18n-tooltip');
    const vars = parseVars(el);
    el.setAttribute('data-tooltip', t(key, vars));
  }
  if (el.hasAttribute('data-i18n-value')) {
    const key = el.getAttribute('data-i18n-value');
    const vars = parseVars(el);
    el.setAttribute('value', t(key, vars));
  }
  if (el.hasAttribute('data-i18n-aria')) {
    const key = el.getAttribute('data-i18n-aria');
    const vars = parseVars(el);
    el.setAttribute('aria-label', t(key, vars));
  }
}

function applyTranslations(root = document) {
  const scope = root.querySelectorAll
    ? root.querySelectorAll('[data-i18n],[data-i18n-html],[data-i18n-placeholder],[data-i18n-title],[data-i18n-tooltip],[data-i18n-value],[data-i18n-aria]')
    : [];
  scope.forEach(translateElement);
  const titleEl = document.querySelector('title[data-i18n]');
  if (titleEl) {
    const key = titleEl.getAttribute('data-i18n');
    titleEl.textContent = t(key);
  }
}

function updateLanguageToggleUI() {
  const lang = getLanguage();
  document.querySelectorAll('[data-lang-toggle]').forEach(group => {
    group.querySelectorAll('button[data-lang]').forEach(btn => {
      const isActive = btn.getAttribute('data-lang') === lang;
      btn.classList.toggle('active', isActive);
      btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
    });
  });
}

function initLanguageToggle() {
  document.querySelectorAll('[data-lang-toggle]').forEach(group => {
    group.querySelectorAll('button[data-lang]').forEach(btn => {
      btn.addEventListener('click', () => {
        setLanguage(btn.getAttribute('data-lang'));
      });
    });
  });
  updateLanguageToggleUI();
}

function observeTranslations() {
  const target = document.body;
  if (!target || typeof MutationObserver === 'undefined') return;
  const observer = new MutationObserver(mutations => {
    mutations.forEach(m => {
      m.addedNodes.forEach(node => {
        if (node.nodeType === 1) {
          translateElement(node);
          if (node.querySelectorAll) {
            node.querySelectorAll('[data-i18n],[data-i18n-html],[data-i18n-placeholder],[data-i18n-title],[data-i18n-tooltip],[data-i18n-value],[data-i18n-aria]').forEach(translateElement);
          }
        }
      });
    });
  });
  observer.observe(target, { childList: true, subtree: true });
}

